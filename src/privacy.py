"""
privacy.py - Ke toan quyen rieng tu (RDP accountant) cho DP-SGD voi Poisson sampling.

Tu chua (khong can Opacus). Cong thuc Sampled Gaussian Mechanism voi bac nguyen alpha
(Mironov, Talwar, Zhang 2019):
    A_a  = sum_{k=0..a} C(a,k) (1-q)^(a-k) q^k exp((k^2-k) / (2 sigma^2))
    RDP(a) = log(A_a) / (a-1)
RDP cong tuyen tinh qua cac buoc / cac round. Doi sang (epsilon, delta) bang cong thuc
chat hon cua Balle et al. 2020 (giong Opacus).
"""
import math
import secrets
from pathlib import Path

import numpy as np

from common import load_json, save_json

ORDERS = list(range(2, 257))


def _log_a(q: float, sigma: float, alpha: int) -> float:
    if q >= 1.0:
        return alpha * (alpha - 1) / (2 * sigma ** 2)
    terms = []
    for k in range(alpha + 1):
        log_binom = math.lgamma(alpha + 1) - math.lgamma(k + 1) - math.lgamma(alpha - k + 1)
        t = log_binom + k * math.log(q) + (alpha - k) * math.log1p(-q) + (k * k - k) / (2 * sigma ** 2)
        terms.append(t)
    m = max(terms)
    return m + math.log(sum(math.exp(t - m) for t in terms))


def compute_rdp(q: float, sigma: float, steps: int, orders=ORDERS):
    if not 0.0 < q <= 1.0:
        raise ValueError("q must be in (0, 1]")
    if sigma <= 0 or steps < 0:
        raise ValueError("sigma must be positive and steps non-negative")
    if q <= 0 or steps == 0:
        return [0.0] * len(orders)
    return [steps * _log_a(q, sigma, a) / (a - 1) for a in orders]


def rdp_to_eps(rdp, delta: float, orders=ORDERS) -> float:
    if not 0.0 < delta < 1.0:
        raise ValueError("delta must be in (0, 1)")
    o = np.asarray(orders, dtype=float)
    r = np.asarray(rdp, dtype=float)
    eps = r - (math.log(delta) + np.log(o)) / (o - 1) + np.log((o - 1) / o)
    return float(np.nanmin(np.maximum(eps, 0.0)))


def secure_rng_seed() -> int:
    """Return a 63-bit seed generated by the operating system CSPRNG."""
    return secrets.randbits(63)


def verify_accountant(q: float, sigma: float, steps: int, delta: float,
                      orders=ORDERS, atol: float = 0.05) -> dict:
    """Compare this accountant with Opacus when it is installed."""
    our_eps = rdp_to_eps(compute_rdp(q, sigma, steps, orders), delta, orders)
    try:
        from opacus.accountants import RDPAccountant
        acc = RDPAccountant()
        acc.history = [(sigma, q, steps)]
        # Match the Renyi orders exactly; otherwise differences can come only
        # from minimizing over different order grids, not from the accountant.
        opacus_eps = acc.get_epsilon(delta=delta, alphas=orders)
        rel_err = abs(our_eps - opacus_eps) / max(opacus_eps, 1e-9)
        return {"our_eps": our_eps, "opacus_eps": opacus_eps,
                "rel_err": rel_err, "ok": rel_err <= atol}
    except Exception as exc:
        return {"our_eps": our_eps, "opacus_eps": None,
                "rel_err": None, "ok": None, "note": str(exc)}


class ClientPrivacyLedger:
    """So cai rieng cua MOT client: compose RDP cua moi lan huan luyen."""

    def __init__(self, path):
        self.path = Path(path)
        self.rounds = load_json(self.path)["rounds"] if self.path.exists() else {}

    def record(self, event_id: str, q: float, sigma: float, steps: int):
        """Record one invocation; rerunning a round is a new privacy event."""
        self.rounds[str(event_id)] = compute_rdp(q, sigma, steps)
        save_json({"orders": ORDERS, "rounds": self.rounds}, self.path)

    def epsilon(self, delta: float, extra=None) -> float:
        """epsilon tich luy. `extra` = (event_id, q, sigma, steps) de du bao."""
        rounds = dict(self.rounds)
        if extra is not None:
            event_id, q, sigma, steps = extra
            rounds[str(event_id)] = compute_rdp(q, sigma, steps)
        total = np.sum([np.asarray(v) for v in rounds.values()], axis=0)
        return rdp_to_eps(total, delta)
